export const getSessionActiveTasks = (session: any): string[] => {
  const ignoredKeys = [
    "id",
    "trainingId",
    "trainingDate",
    "sessionNumber",
    "status",
    "createdAt",
  ];
  return Object.entries(session || {})
    .filter(([key, val]) => !ignoredKeys.includes(key) && val === true)
    .map(([key]) => STAGE_EXERCISE_LABELS[key] || key);
};

